-- Standalone Git repositories (git-repos.md §3; data-model.md §2.15): any Git host (GitLab, Gitea,
-- self-hosted…) added one repository at a time, authenticated with an HTTPS token or an SSH key.
-- The user owns them (like at_remote_servers); projects pick them next to GitHub repositories.
--
-- Credentials are envelope-encrypted exactly like remote server credentials (server/internal/credvault):
-- the AAD binds user_id, credential id, kind, host and username (credvault.GitCredAAD), so a value
-- copied to another row, or left behind after the host / kind / username changed, no longer opens.
-- Nodes never see them: they read and write through the console's Git relay (git-repos.md §5).
CREATE TABLE at_git_credentials (
  id              TEXT PRIMARY KEY,                                            -- gc_…
  user_id         TEXT NOT NULL REFERENCES at_users(id) ON DELETE CASCADE,
  name            TEXT NOT NULL CHECK (name <> ''),
  host            TEXT NOT NULL CHECK (host <> ''),                            -- lowercase host[:port]; only repositories on it may use the credential
  kind            TEXT NOT NULL CHECK (kind IN ('https_token', 'ssh_key')),
  username        TEXT NOT NULL DEFAULT '',                                    -- HTTPS user (oauth2, x-access-token…) or SSH login user (git)
  cred_ciphertext BYTEA NOT NULL,                                              -- AES-256-GCM(DEK, JSON {password} | {private_key, passphrase?})
  cred_nonce      BYTEA NOT NULL,
  wrapped_dek     BYTEA NOT NULL,
  dek_nonce       BYTEA NOT NULL,
  kek_id          TEXT  NOT NULL,
  has_passphrase  BOOLEAN NOT NULL DEFAULT FALSE,
  key_fingerprint TEXT NOT NULL DEFAULT '',                                    -- ssh_key: SHA256:… of its public key
  public_key      TEXT NOT NULL DEFAULT '',                                    -- ssh_key: authorized_keys line (shown so it can be added as a deploy key)
  generated       BOOLEAN NOT NULL DEFAULT FALSE,                              -- ssh_key generated by the console (nobody ever saw the private key)
  expires_at      TIMESTAMPTZ,                                                 -- https_token: expiry the user entered (reminders)
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  cred_updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, name),
  UNIQUE (id, user_id)
);

CREATE TABLE at_git_repos (
  id                    TEXT PRIMARY KEY,                                      -- gr_…; also the relay path /git/<id>.git
  user_id               TEXT NOT NULL REFERENCES at_users(id) ON DELETE CASCADE,
  slug                  TEXT NOT NULL CHECK (slug ~ '^[a-z0-9.-]+(:[0-9]+)?(/[^/]+){1,}$'), -- host[:port]/path: the repo key in projects, threads and tools
  name                  TEXT NOT NULL DEFAULT '',
  url                   TEXT NOT NULL,                                         -- normalised clone URL (https://… or ssh://user@host:port/…)
  transport             TEXT NOT NULL CHECK (transport IN ('https', 'ssh')),
  host                  TEXT NOT NULL,                                         -- lowercase host[:port], as in at_git_credentials.host
  credential_id         TEXT,                                                  -- NULL = public, read only
  provider              TEXT NOT NULL DEFAULT 'generic' CHECK (provider IN ('github', 'gitlab', 'gitea', 'bitbucket', 'generic')),
  web_url               TEXT NOT NULL DEFAULT '',
  default_branch        TEXT NOT NULL DEFAULT '',                              -- from the last successful test / sync
  access                TEXT NOT NULL DEFAULT '' CHECK (access IN ('', 'read', 'write')),
  host_key              TEXT NOT NULL DEFAULT '',                              -- ssh: pinned host key (authorized_keys line)
  host_key_fp           TEXT NOT NULL DEFAULT '',
  host_key_mac          BYTEA,                                                 -- HMAC (credvault.GitHostKeyMACData) under a KEK-derived key
  host_key_confirmed_at TIMESTAMPTZ,
  last_checked_at       TIMESTAMPTZ,
  last_error            TEXT NOT NULL DEFAULT '',
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, slug),
  UNIQUE (id, user_id),
  FOREIGN KEY (credential_id, user_id) REFERENCES at_git_credentials (id, user_id) ON DELETE RESTRICT
);
CREATE INDEX at_git_repos_credential ON at_git_repos (credential_id) WHERE credential_id IS NOT NULL;

-- A project repository comes from a GitHub connection (git_connection_id) or is a standalone
-- repository (git_repo_id). A standalone repository still used by a project cannot be deleted.
ALTER TABLE at_project_repos
  ADD COLUMN git_repo_id TEXT REFERENCES at_git_repos(id) ON DELETE RESTRICT,
