func parseRepoURL(raw string) (gitremote.Parsed, error) {
	parsed, err := gitremote.ParseURL(raw)
	if err != nil {
		msg := strings.TrimPrefix(err.Error(), gitremote.ErrURL.Error()+": ")
		return parsed, invalid([]FieldError{{Path: "body.url", Message: msg}}, msg)
	}
	return parsed, nil
}

func (s *Server) createGitRepo(ctx context.Context, in *createGitRepoInput) (*gitRepoOutput, error) {
	p, err := requireUser(ctx)
	if err != nil {
		return nil, err
	}
	b := in.Body
	parsed, err := parseRepoURL(b.URL)
	if err != nil {
		return nil, err
	}
	if err := s.checkTarget(ctx, parsed.Hostname); err != nil {
		return nil, err
	}
	if b.Provider != "" && !gitProviders[b.Provider] {
		return nil, invalid([]FieldError{{Path: "body.provider", Message: "未知平台"}}, "未知平台")
	}
	if err := checkWebURL(b.WebURL); err != nil {
		return nil, err
	}
	credID := b.CredentialID
	if credID != nil && *credID == "" {
		credID = nil
	}
	if b.Credential != nil {
		nc := *b.Credential
		nc.Host = parsed.Host
		if nc.Kind == "" {
			nc.Kind = map[string]string{"https": credvault.GitHTTPSToken, "ssh": credvault.GitSSHKey}[parsed.Transport]
		}
		if nc.Username == "" {
			nc.Username = parsed.DefaultUsername
		}
		c, err := s.newGitCredential(ctx, p.User.ID, nc)
		if err != nil {
			return nil, err
		}
		credID = &c.ID
	}
	if credID != nil {
		if err := s.checkCredForRepo(ctx, p.User.ID, *credID, parsed); err != nil {
			return nil, err
		}
	}
	provider, webURL := orStr(b.Provider, parsed.Provider), orStr(b.WebURL, parsed.WebURL)
	repo := store.GitRepo{ID: store.NewID("gr"), UserID: p.User.ID, Slug: parsed.Slug, Name: strings.TrimSpace(b.Name), URL: parsed.URL,
		Transport: parsed.Transport, Host: parsed.Host, CredentialID: credID, Provider: provider, WebURL: webURL}
	row, err := s.store.CreateGitRepo(ctx, repo)
	if err != nil {
		return nil, gitStoreErr(err, "凭据")
	}
	s.audit(ctx, p.User.ID, "git_repo_create", "git_repo", row.ID, map[string]any{"slug": row.Slug, "url": row.URL, "credential_id": row.CredentialID})
	if res, err := s.runSavedGitTest(ctx, p.User.ID, row); err == nil && !res.OK {
		s.log.Info("new git repo test failed", "repo", row.ID, "error", res.Error)
	}
	if fresh, err := s.store.GitRepo(ctx, p.User.ID, row.ID); err == nil {
		row = fresh
	}
	return &gitRepoOutput{Body: gitRepoView(row, nil)}, nil
}

func orStr(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

// checkCredForRepo: the credential is the user's, of the URL's host, and of the URL's transport.
func (s *Server) checkCredForRepo(ctx context.Context, userID, credID string, parsed gitremote.Parsed) error {
	c, err := s.store.GitCredential(ctx, userID, credID)
	if err != nil {
		return gitStoreErr(err, "凭据")
	}
	want := map[string]string{"https": credvault.GitHTTPSToken, "ssh": credvault.GitSSHKey}[parsed.Transport]
	switch {
	case c.Host != parsed.Host:
		return fail(http.StatusUnprocessableEntity, "host_mismatch", "凭据属于 "+c.Host+"，不能用在 "+parsed.Host+" 的仓库上")
	case c.Kind != want:
		return fail(http.StatusUnprocessableEntity, "kind_mismatch", "HTTPS 地址要用令牌，SSH 地址要用 SSH 私钥")
	}
	return nil
}

func (s *Server) updateGitRepo(ctx context.Context, in *updateGitRepoInput) (*gitRepoOutput, error) {
	p, err := requireUser(ctx)
	if err != nil {
		return nil, err
	}
	b := in.Body
	cur, err := s.store.GitRepo(ctx, p.User.ID, in.ID)
	if err != nil {
		return nil, gitStoreErr(err, "仓库")
	}
	patch := store.GitRepoPatch{Name: trimPtr(b.Name), WebURL: trimPtr(b.WebURL), Provider: b.Provider}
	if b.Provider != nil && !gitProviders[*b.Provider] {
		return nil, invalid([]FieldError{{Path: "body.provider", Message: "未知平台"}}, "未知平台")
	}
	if patch.WebURL != nil {
		if err := checkWebURL(*patch.WebURL); err != nil {
			return nil, err
		}
	}
	if b.CredentialID != nil {
		var id *string
		if *b.CredentialID != "" {
			parsed, err := gitremote.ParseURL(cur.URL)
			if err != nil {
				return nil, err
			}
			if err := s.checkCredForRepo(ctx, p.User.ID, *b.CredentialID, parsed); err != nil {
				return nil, err
			}
			id = b.CredentialID
		}
		patch.CredentialID = &id
	}
	row, err := s.store.UpdateGitRepo(ctx, p.User.ID, in.ID, patch)
	if err != nil {
		return nil, gitStoreErr(err, "仓库")
	}
	s.audit(ctx, p.User.ID, "git_repo_update", "git_repo", row.ID, map[string]any{"name": row.Name, "credential_id": row.CredentialID,
		"provider": row.Provider, "web_url": row.WebURL})
	v, err := s.oneGitRepoView(ctx, p.User.ID, row)
	return &gitRepoOutput{Body: v}, err
}

func (s *Server) deleteGitRepo(ctx context.Context, in *gitIDInput) (*struct{}, error) {
	p, err := requireUser(ctx)
	if err != nil {
		return nil, err
	}
	if err := s.store.DeleteGitRepo(ctx, p.User.ID, in.ID); err != nil {
		if errors.Is(err, store.ErrInUse) {
			used, _ := s.store.GitRepoProjects(ctx, p.User.ID)
			names := make([]string, 0, len(used[in.ID]))
			for _, pr := range used[in.ID] {
				names = append(names, pr.Name)
			}
			return nil, fail(http.StatusConflict, "in_use", "还有项目在用这个仓库："+strings.Join(names, "、")+"。先在项目设置里移除")
		}
		return nil, gitStoreErr(err, "仓库")
	}
	s.audit(ctx, p.User.ID, "git_repo_delete", "git_repo", in.ID, nil)
	if err := s.relay.Remove(in.ID); err != nil {
		s.log.Warn("remove git mirror", "repo", in.ID, "err", err)
	}
	return nil, nil
}

