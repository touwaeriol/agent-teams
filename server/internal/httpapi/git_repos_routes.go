func gitStoreErr(err error, notFound string) error {
	switch {
	case errors.Is(err, store.ErrInUse):
		return fail(http.StatusConflict, "in_use", "还在使用中，不能删除："+notFound)
	case errors.Is(err, store.ErrHostMismatch):
		return fail(http.StatusUnprocessableEntity, "host_mismatch", store.ErrHostMismatch.Error())
	case errors.Is(err, store.ErrCredentialRequired):
		return fail(http.StatusUnprocessableEntity, "credential_required", "改了用户名，必须同时重新填写令牌或私钥")
	case errors.Is(err, store.ErrConflict) && strings.Contains(err.Error(), "slug"):
		return fail(http.StatusConflict, "repo_exists", "这个仓库已经添加过了")
	case errors.Is(err, store.ErrConflict):
		return fail(http.StatusConflict, "name_taken", "已经有同名的凭据了")
	}
	return storeErr(err, "没有找到："+notFound)
}

var gitProviders = map[string]bool{"github": true, "gitlab": true, "gitea": true, "bitbucket": true, "generic": true}

func checkWebURL(u string) error {
	if u == "" || strings.HasPrefix(u, "https://") && !strings.ContainsAny(u, " \n\"'<>") {
		return nil
	}
	return invalid([]FieldError{{Path: "body.web_url", Message: "网页地址要以 https:// 开头"}}, "网页地址要以 https:// 开头")
}

// sealGit checks and seals a credential value for c (its final user, id, kind, host, username).
func (s *Server) sealGit(c store.GitCredential, in GitSecretInput) (*store.GitSealed, error) {
	if err := s.requireVault(); err != nil {
		return nil, err
	}
	authKind, err := credvault.GitAuthKind(c.Kind)
	if err != nil {
		return nil, credErr(err)
	}
	cred := credvault.Credential{Password: strings.TrimSpace(in.Token)}
	out := &store.GitSealed{}
	if c.Kind == credvault.GitSSHKey {
		cred = credvault.Credential{Passphrase: in.Passphrase}
		if in.Generate {
			gen, info, err := credvault.GenerateSSHKey("agent-teams")
			if err != nil {
				return nil, err
			}
			cred, out.Generated, out.PublicKey = gen, true, info.PublicKey
		} else if key := strings.TrimSpace(in.PrivateKey); key != "" {
			cred.PrivateKey = key + "\n"
		}
	}
	sealed, info, err := s.vault.SealCredential(credvault.GitCredAAD(c.UserID, c.ID, c.Kind, c.Host, c.Username), authKind, cred)
	if err != nil {
		return nil, credErr(err)
	}
	out.Sealed, out.HasPassphrase, out.KeyFingerprint = sealed, cred.Passphrase != "", info.Fingerprint
	if out.PublicKey == "" {
		out.PublicKey = info.PublicKey
	}
	return out, nil
}

var gitHostRE = regexp.MustCompile(`^[a-z0-9]([a-z0-9.-]*[a-z0-9])?(:[0-9]{1,5})?$`)

func (s *Server) newGitCredential(ctx context.Context, userID string, in GitCredentialInput) (store.GitCredential, error) {
	in.Name, in.Host, in.Username = strings.TrimSpace(in.Name), strings.ToLower(strings.TrimSpace(in.Host)), strings.TrimSpace(in.Username)
	if in.Name == "" {
		in.Name = in.Host
	}
	if _, err := credvault.GitAuthKind(in.Kind); err != nil {
		return store.GitCredential{}, invalid([]FieldError{{Path: "body.kind", Message: "凭据类型要选 HTTPS 令牌或 SSH 私钥"}}, "凭据类型要选 HTTPS 令牌或 SSH 私钥")
	}
	if !gitHostRE.MatchString(in.Host) {
		return store.GitCredential{}, invalid([]FieldError{{Path: "body.host", Message: "主机不合法"}}, "主机不合法")
	}
	if in.Kind == credvault.GitSSHKey && in.Username == "" {
		in.Username = "git"
	}
	if in.Username != "" && !usernameRE.MatchString(in.Username) {
		return store.GitCredential{}, invalid([]FieldError{{Path: "body.username", Message: "用户名不合法"}}, "用户名不合法")
	}
	if in.Kind == credvault.GitHTTPSToken && in.Username == "" {
		return store.GitCredential{}, invalid([]FieldError{{Path: "body.username", Message: "HTTPS 令牌要填用户名"}}, "HTTPS 令牌要填用户名")
	}
	c := store.GitCredential{ID: store.NewID("gc"), UserID: userID, Name: in.Name, Host: in.Host, Kind: in.Kind, Username: in.Username,
		ExpiresAt: in.ExpiresAt}
	sealed, err := s.sealGit(c, in.GitSecretInput)
	if err != nil {
		return store.GitCredential{}, err
	}
	row, err := s.store.CreateGitCredential(ctx, c, *sealed)
	if err != nil {
		return store.GitCredential{}, gitStoreErr(err, "凭据")
	}
	s.audit(ctx, userID, "git_credential_create", "git_credential", row.ID, map[string]any{"name": row.Name, "host": row.Host,
		"kind": row.Kind, "generated": row.Generated})
	return row, nil
}

