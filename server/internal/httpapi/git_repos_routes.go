// runSavedGitTest tests a saved repository, pins the SSH host key the first time and records the
// outcome on the row.
func (s *Server) runSavedGitTest(ctx context.Context, userID string, r store.GitRepo) (GitTestResult, error) {
	remote, err := s.GitRemote(ctx, userID, r)
	if err != nil {
		res := GitTestResult{Error: "credential_unreadable", Message: err.Error()}
		_ = s.store.RecordGitRepoCheck(ctx, r.ID, store.GitRepoCheck{Error: res.Message})
		return res, nil
	}
	res, seen := s.runGitTest(ctx, remote)
	if seen != nil && r.HostKey == "" && res.Error != "host_key_mismatch" {
		mac, merr := s.vault.MAC(credvault.GitHostKeyMACData(r.ID, r.Host, seen.Line))
		if merr == nil {
			pinned, perr := s.store.PinGitRepoHostKey(ctx, userID, r.ID, seen.Line, seen.Fingerprint, mac)
			if perr != nil {
				s.log.Warn("pin git host key", "repo", r.ID, "err", perr)
			}
			res.HostKeyPinned = pinned
			if pinned {
				s.audit(ctx, userID, "git_repo_host_key_pin", "git_repo", r.ID, map[string]string{"fingerprint": seen.Fingerprint})
			}
		}
	}
	check := store.GitRepoCheck{Access: res.Access, DefaultBranch: res.DefaultBranch}
	if !res.OK {
		check.Error = res.Message
	}
	if err := s.store.RecordGitRepoCheck(ctx, r.ID, check); err != nil {
		s.log.Warn("record git check", "repo", r.ID, "err", err)
	}
	return res, nil
}

// GitRemote opens a saved repository's credential and checks its pinned host key's MAC: the
// upstream as the console uses it (test connection, relay, delivery).
