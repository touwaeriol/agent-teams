// OpenGitRemote is GitRemote for callers outside the HTTP server.
func OpenGitRemote(ctx context.Context, st *store.Store, v *credvault.Vault, policy sshdial.Policy, userID string, r store.GitRepo) (gitremote.Remote, error) {
	return gitrelay.OpenRemote(ctx, st, v, policy, userID, r)
}

func (s *Server) testGitRepoDraft(ctx context.Context, in *testGitRepoInput) (*gitTestOutput, error) {
	p, err := requireUser(ctx)
	if err != nil {
		return nil, err
	}
	b := in.Body
	parsed, err := parseRepoURL(b.URL)
	if err != nil {
		return nil, err
	}
	if err := s.gitTestLimits(ctx, p.User.ID, "draft"); err != nil {
		return nil, err
	}
	remote := gitremote.Remote{URL: parsed.URL, Transport: parsed.Transport, Policy: s.sshPolicy(ctx)}
	switch {
	case b.CredentialID != nil && *b.CredentialID != "":
		if err := s.checkCredForRepo(ctx, p.User.ID, *b.CredentialID, parsed); err != nil {
			return nil, err
		}
		if remote, err = OpenGitRemote(ctx, s.store, s.vault, remote.Policy, p.User.ID, store.GitRepo{URL: parsed.URL,
			Transport: parsed.Transport, Host: parsed.Host, CredentialID: b.CredentialID}); err != nil {
			return &gitTestOutput{Body: GitTestResult{Error: "credential_unreadable", Message: err.Error()}}, nil
		}
	case b.Credential != nil:
		c := b.Credential
		if c.Generate {
			return nil, invalid([]FieldError{{Path: "body.credential.generate", Message: "先生成并保存密钥，再测试"}}, "先生成并保存密钥，再测试")
		}
		remote.Username = orStr(strings.TrimSpace(c.Username), parsed.DefaultUsername)
		if parsed.Transport == "https" {
			remote.Kind, remote.Cred = credvault.GitHTTPSToken, credvault.Credential{Password: strings.TrimSpace(c.Token)}
		} else {
			remote.Kind = credvault.GitSSHKey
			remote.Cred = credvault.Credential{PrivateKey: strings.TrimSpace(c.PrivateKey) + "\n", Passphrase: c.Passphrase}
			if _, err := remote.Cred.Check(credvault.AuthPrivateKey); err != nil {
				return nil, credErr(err)
			}
		}
	}
	res, _ := s.runGitTest(ctx, remote)
	return &gitTestOutput{Body: res}, nil
}

// runGitTest: (ssh) log in once in-process to see the host key and check the credential, then
// ls-remote for the branches and a receive-pack probe for write access.
func (s *Server) runGitTest(ctx context.Context, r gitremote.Remote) (GitTestResult, *sshdial.HostKey) {
	ctx, cancel := context.WithTimeout(ctx, gitTestTimeout)
	defer cancel()
	start := time.Now()
	var res GitTestResult
	var seen *sshdial.HostKey
	if r.Transport == "ssh" {
		host, port, err := r.HostPort()
		if err != nil {
			return GitTestResult{Error: "failed", Message: err.Error()}, nil
		}
		if r.Kind == "" {
			return GitTestResult{Error: "auth_failed", Message: "SSH 地址需要 SSH 私钥"}, nil
		}
		dial, err := r.Policy.Dial(ctx, sshdial.Target{Host: host, Port: port, Username: r.Username, AuthKind: credvault.AuthPrivateKey,
			Cred: r.Cred, HostKey: r.HostKey}, gitTestTimeout)
		seen = dial.Seen
		if seen != nil {
			res.HostKeyFP, res.HostKeyType = seen.Fingerprint, seen.Type
		}
		if dial.Client != nil {
			_ = dial.Client.Close()
		}
		if err != nil {
			res.Error, res.Message = sshTestError(err, host)
			res.LatencyMS = time.Since(start).Milliseconds()
			return res, seen
		}
		if r.HostKey == "" && seen != nil {
			r.HostKey = seen.Line // the same key for the git commands below
		}
	}
	refs, err := s.gitRunner().LsRemote(ctx, r)
	res.LatencyMS = time.Since(start).Milliseconds()
	if err != nil {
		res.Error, res.Message = gitTestError(err)
		return res, seen
	}
	res.OK, res.DefaultBranch, res.Branches, res.Access = true, refs.Head, len(refs.Branches), "read"
	if ok, err := s.gitRunner().CanPush(ctx, r); err == nil && ok {
		res.Access = "write"
	}
	return res, seen
}

func (s *Server) gitRunner() gitremote.Git { return s.git }

func sshTestError(err error, host string) (string, string) {
	switch {
	case errors.Is(err, sshdial.ErrHostKeyMismatch):
		return "host_key_mismatch", "主机密钥和已固定的不一样，没有发送凭据。确认服务器没被冒充后重置主机密钥再测试"
	case errors.Is(err, sshdial.ErrAuth):
		return "auth_failed", "认证失败：私钥不对，或部署密钥还没添加到仓库"
	case errors.Is(err, sshdial.ErrBlockedAddress):
		return "address_blocked", err.Error()
	case errors.Is(err, sshdial.ErrResolve), errors.Is(err, sshdial.ErrInvalidHost):
		return "resolve_failed", "主机名解析不到地址：" + host
	case errors.Is(err, sshdial.ErrTimeout):
		return "timeout", "连接超时"
	case errors.Is(err, sshdial.ErrConnect):
		return "connect_failed", "连不上 " + host + "，请检查地址和端口"
	case errors.Is(err, credvault.ErrInvalidCredential):
		return "credential_unreadable", err.Error()
	}
	return "failed", "SSH 握手失败：" + err.Error()
}

func gitTestError(err error) (string, string) {
	switch {
	case errors.Is(err, gitremote.ErrAuth):
		return "auth_failed", "认证失败：令牌或私钥不对、已过期，或没有这个仓库的权限"
	case errors.Is(err, gitremote.ErrNotFound):
		return "repo_not_found", "仓库不存在，或凭据看不到它"
	case errors.Is(err, gitremote.ErrHostKey):
		return "host_key_mismatch", "主机密钥和已固定的不一样"
	case errors.Is(err, sshdial.ErrBlockedAddress):
		return "address_blocked", err.Error()
	case errors.Is(err, sshdial.ErrResolve), errors.Is(err, sshdial.ErrInvalidHost):
		return "resolve_failed", "主机名解析不到地址"
	case errors.Is(err, gitremote.ErrConnect):
		return "connect_failed", "连不上仓库所在的主机"
	case errors.Is(err, context.DeadlineExceeded):
		return "timeout", "连接超时"
	}
	return "failed", err.Error()
}

func (s *Server) gitRepoBranches(ctx context.Context, in *gitBranchesInput) (*gitBranchesOutput, error) {
	p, err := requireUser(ctx)
	if err != nil {
		return nil, err
	}
	r, err := s.store.GitRepo(ctx, p.User.ID, in.ID)
	if err != nil {
		return nil, gitStoreErr(err, "仓库")
	}
	remote, err := s.GitRemote(ctx, p.User.ID, r)
	if err != nil {
		return nil, fail(http.StatusConflict, "credential_unreadable", err.Error())
	}
	ctx, cancel := context.WithTimeout(ctx, gitTestTimeout)
	defer cancel()
	refs, err := s.gitRunner().LsRemote(ctx, remote)
	if err != nil {
		_, msg := gitTestError(err)
		return nil, fail(http.StatusBadGateway, "git_failed", msg)
	}
	out := make([]string, 0, len(refs.Branches))
	q := strings.ToLower(in.Q)
	for b := range refs.Branches {
		if q == "" || strings.Contains(strings.ToLower(b), q) {
			out = append(out, b)
		}
	}
	sortBranches(out, refs.Head)
	if len(out) > 100 {
		out = out[:100]
	}
	return &gitBranchesOutput{Body: out}, nil
}

// sortBranches puts the default branch first, then the rest by name.
func sortBranches(list []string, head string) {
	sort.Slice(list, func(i, j int) bool {
		if (list[i] == head) != (list[j] == head) {
			return list[i] == head
		}
		return list[i] < list[j]
	})
}
