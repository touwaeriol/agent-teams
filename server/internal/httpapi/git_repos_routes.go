// GitCredentialView is a credential without its secret.
type GitCredentialView struct {
	ID             string     `json:"id"`
	Name           string     `json:"name"`
	Host           string     `json:"host" doc:"host[:port] the credential may be used on"`
	Kind           string     `json:"kind" enum:"https_token,ssh_key"`
	Username       string     `json:"username"`
	HasPassphrase  bool       `json:"has_passphrase"`
	KeyFingerprint string     `json:"key_fingerprint"`
	PublicKey      string     `json:"public_key" doc:"ssh_key: public key to add as a deploy key"`
	Generated      bool       `json:"generated" doc:"ssh_key generated by the platform (the private key was never shown)"`
	ExpiresAt      *time.Time `json:"expires_at" nullable:"true"`
	Repos          int        `json:"repos" doc:"Repositories using it"`
	CredUpdatedAt  time.Time  `json:"cred_updated_at"`
	CreatedAt      time.Time  `json:"created_at"`
}

func gitCredentialView(c store.GitCredential, repos int) GitCredentialView {
	return GitCredentialView{ID: c.ID, Name: c.Name, Host: c.Host, Kind: c.Kind, Username: c.Username, HasPassphrase: c.HasPassphrase,
		KeyFingerprint: c.KeyFingerprint, PublicKey: c.PublicKey, Generated: c.Generated, ExpiresAt: c.ExpiresAt, Repos: repos,
		CredUpdatedAt: c.CredUpdatedAt, CreatedAt: c.CreatedAt}
}

// GitRepoView is a standalone repository.
