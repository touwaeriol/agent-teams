// Writes the Go side that go-jsonschema does not produce:
//   gen/go/registry.gen.go  - message type constants and metadata, tool metadata, body/input/result constructors
//   gen/go/schemas/**       - copy of protocol/schemas for go:embed (runtime validation)
//   gen/go/manifest.json    - copy of gen/manifest.json for go:embed (tool input schemas)
// Run after go-jsonschema produced gen/go/types.gen.go (see Makefile target gen-protocol).
// Usage: node scripts/gen-go.mjs
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, SCHEMAS, pascal, readJson } from "./lib.mjs";

const OUT = join(ROOT, "gen/go");
const BANNER = "// Code generated by protocol/scripts/gen-go.mjs, DO NOT EDIT.";

function goTypeNames() {
  const src = readFileSync(join(OUT, "types.gen.go"), "utf8");
  const names = [...src.matchAll(/^type (\w+) /gm)].map((m) => m[1]);
  return new Map(names.map((n) => [n.toLowerCase(), n]));
}

function goName(names, title) {
  const name = names.get(title.toLowerCase());
  if (!name) throw new Error(`go-jsonschema produced no type for ${title}`);
  return name;
}

function goStrings(list) {
  return list.length ? `[]string{${list.map((s) => JSON.stringify(s)).join(", ")}}` : "nil";
}

function goTiers(list) {
  return list.length ? `[]Tier{${list.map((t) => `Tier${pascal(t)}`).join(", ")}}` : "nil";
}

const DIRECTION = { console_to_node: "ConsoleToNode", node_to_console: "NodeToConsole", both: "Both" };

function messageBlock(messages, names) {
  const lines = ["// Node message types (envelope \"type\").", "const ("];
  for (const m of messages) lines.push(`\tType${pascal(m.type)} = ${JSON.stringify(m.type)}`);
  lines.push(")", "", "// Messages describes every node message type.", "var Messages = map[string]MessageMeta{");
  for (const m of messages) {
    const type = goName(names, m.name);
    lines.push(`\tType${pascal(m.type)}: {Direction: ${DIRECTION[m.direction]}, Reliable: ${m.reliable}, Key: ${goStrings(m.key)}, New: func() any { return new(${type}) }},`);
  }
  lines.push("}", "");
  return lines;
}

function toolBlock(tools, names) {
  const lines = ["// Platform tool names.", "const ("];
  for (const t of tools) lines.push(`\tTool${pascal(t.name)} = ${JSON.stringify(t.name)}`);
  lines.push(")", "", "// Tools describes every platform tool.", "var Tools = map[string]ToolMeta{");
  for (const t of tools) {
    const result = t.result ? `func() any { return new(${goName(names, t.result)}) }` : "nil";
    lines.push(`\tTool${pascal(t.name)}: {`);
    lines.push(`\t\tTiers: ${goTiers(t.tiers)}, Blocking: ${goTiers(t.blocking)}, Requires: ${JSON.stringify(t.requires ?? "")},`);
    lines.push(`\t\tNewInput: func() any { return new(${goName(names, t.input)}) }, NewResult: ${result},`);
    lines.push("\t},");
  }
  lines.push("}", "");
  return lines;
}

function registry(manifest) {
  const names = goTypeNames();
  return [BANNER, "", "package protocol", "", ...messageBlock(manifest.messages, names), ...toolBlock(manifest.tools, names)].join("\n");
}

function run() {
  mkdirSync(OUT, { recursive: true });
  const manifest = readJson(join(ROOT, "gen/manifest.json"));
  writeFileSync(join(OUT, "registry.gen.go"), registry(manifest));
  writeFileSync(join(OUT, "manifest.json"), readFileSync(join(ROOT, "gen/manifest.json")));
  rmSync(join(OUT, "schemas"), { recursive: true, force: true });
  cpSync(SCHEMAS, join(OUT, "schemas"), { recursive: true });
}

run();
