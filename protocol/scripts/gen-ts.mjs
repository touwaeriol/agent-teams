// Generates TypeScript types into gen/ts from gen/bundle.schema.json (json-schema-to-typescript)
// plus a hand-shaped registry (message type -> body type, metadata, tool maps) from gen/manifest.json.
// Usage: node scripts/gen-ts.mjs [--check]
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { compile } from "json-schema-to-typescript";
import { ROOT, SCHEMAS, readJson } from "./lib.mjs";

const OUT = join(ROOT, "gen/ts");
const BANNER = "/* GENERATED by protocol/scripts/gen-ts.mjs from protocol/schemas. Do not edit; run `make gen`. */";
const OPTIONS = {
  bannerComment: BANNER,
  unreachableDefinitions: true,
  additionalProperties: false,
  format: true,
  style: { singleQuote: false, printWidth: 110 },
};

function quote(s) {
  return JSON.stringify(s);
}

function registry(manifest) {
  const { messages, tools } = manifest;
  const lines = [BANNER, `import type * as T from "./types.js";`, ""];
  lines.push("/** Body type of every node message, keyed by envelope type. */");
  lines.push("export interface MessageBodies {");
  for (const m of messages) lines.push(`  ${quote(m.type)}: T.${m.name};`);
  lines.push("}", "");
  lines.push("export type MessageType = keyof MessageBodies;", "");
  lines.push("/** Envelope with the body typed by its message type. */");
  lines.push("export type Message<K extends MessageType = MessageType> = {");
  lines.push("  [P in K]: Omit<T.Envelope, \"type\" | \"body\"> & { type: P; body: MessageBodies[P] };");
  lines.push("}[K];", "");
  lines.push("export type Direction = \"console_to_node\" | \"node_to_console\" | \"both\";");
  lines.push("export interface MessageMeta { direction: Direction; reliable: boolean; key: readonly string[] }", "");
  lines.push("export const MESSAGE_META: { readonly [K in MessageType]: MessageMeta } = {");
  for (const m of messages) {
    lines.push(`  ${quote(m.type)}: { direction: ${quote(m.direction)}, reliable: ${m.reliable}, key: ${JSON.stringify(m.key)} },`);
  }
  lines.push("};", "");
  lines.push("/** Input type of every platform tool. */");
  lines.push("export interface ToolInputs {");
  for (const t of tools) lines.push(`  ${t.name}: T.${t.input};`);
  lines.push("}", "");
  lines.push("/** Structured result type of every platform tool (unknown when it only returns text). */");
  lines.push("export interface ToolResults {");
  for (const t of tools) lines.push(`  ${t.name}: ${t.result ? `T.${t.result}` : "unknown"};`);
  lines.push("}", "");
  lines.push("export type ToolName = keyof ToolInputs;");
  lines.push("export interface ToolMeta {\n  tiers: readonly T.Tier[];\n  blocking: readonly T.Tier[];\n  requires: string | null;\n  description: string;\n  /** Self-contained JSON Schema sent as session.open platform_tools[].input_schema. */\n  input_schema: Record<string, unknown>;\n}", "");
  lines.push("export const TOOL_META: { readonly [K in ToolName]: ToolMeta } = {");
  for (const t of tools) {
    const req = t.requires ? quote(t.requires) : "null";
    lines.push(`  ${t.name}: {`);
    lines.push(`    tiers: ${JSON.stringify(t.tiers)},`);
    lines.push(`    blocking: ${JSON.stringify(t.blocking)},`);
    lines.push(`    requires: ${req},`);
    lines.push(`    description: ${quote(t.description)},`);
    lines.push(`    input_schema: ${JSON.stringify(t.input_schema)},`);
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

const INDEX = `${BANNER}
export type * from "./types.js";
export type * as Office from "./office.js";
export type { OfficeLayout } from "./office.js";
export * from "./registry.js";
`;

function emit(name, text, check, stale) {
  const path = join(OUT, name);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === text) return;
  stale.push(path);
  if (!check) writeFileSync(path, text);
}

async function run(check) {
  mkdirSync(OUT, { recursive: true });
  const bundle = readJson(join(ROOT, "gen/bundle.schema.json"));
  const office = readJson(join(SCHEMAS, "office/office-layout.schema.json"));
  const manifest = readJson(join(ROOT, "gen/manifest.json"));
  const stale = [];
  emit("types.ts", await compile(bundle, "Envelope", OPTIONS), check, stale);
  emit("office.ts", await compile({ ...office, title: "OfficeLayout" }, "OfficeLayout", { ...OPTIONS, additionalProperties: undefined }), check, stale);
  emit("registry.ts", registry(manifest), check, stale);
  emit("index.ts", INDEX, check, stale);
  if (check && stale.length) {
    console.error("stale generated files (run make gen):\n  " + stale.join("\n  "));
    process.exit(1);
  }
}

await run(process.argv.includes("--check"));
