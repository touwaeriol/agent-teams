// Derives the generated schemas from the hand-written sources:
//   schemas/node/message.json  - discriminated union of every node message (for validation)
//   gen/bundle.schema.json     - one self-contained schema with every type in $defs (for code generators)
//   gen/manifest.json          - message types (direction, reliability, key) and tools (tiers, blocking)
// Usage: node scripts/bundle.mjs [--check]
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, posix } from "node:path";
import {
  DRAFT, GENERATED_MESSAGE, ROOT, SCHEMAS, loadSchema, messageSchemas, schemaFiles, schemaId,
  toolSchemas, writeJsonText,
} from "./lib.mjs";

const ID_PREFIX = { console_to_node: "^c_", node_to_console: "^n_" };

function messageVariant({ type, schema }) {
  const props = { type: { const: type }, body: { $ref: `${type}.json` } };
  const prefix = ID_PREFIX[schema["x-direction"]];
  if (prefix) props.id = { type: "string", pattern: prefix };
  const variant = { properties: props, required: ["type", "body"] };
  if (schema["x-reliable"]) variant.required.push("seq");
  else variant.not = { required: ["seq"] };
  return variant;
}

export function buildMessageSchema() {
  return {
    $schema: DRAFT,
    $id: schemaId(GENERATED_MESSAGE),
    title: "NodeMessage",
    description:
      "GENERATED by scripts/bundle.mjs from the x-direction/x-reliable metadata of every node message schema. " +
      "Any frame on the node WebSocket: the envelope plus the body schema selected by type. Reliable types require seq, unreliable ones must not carry it; " +
      "console->node ids start with c_, node->console ids with n_.",
    $ref: "envelope.json",
    type: "object",
    required: ["type"],
    discriminator: { propertyName: "type" },
    oneOf: messageSchemas().map(messageVariant),
  };
}

// ---- bundle for code generators ----------------------------------------------------------

const VALIDATION_ONLY = new Set(["if", "then", "else", "not", "discriminator", "$schema", "$id"]);

function isRequiredOnly(item) {
  return Object.keys(item).every((k) => k === "required" || VALIDATION_ONLY.has(k));
}

function isConditional(item) {
  return Object.keys(item).every((k) => VALIDATION_ONLY.has(k));
}

function dropValidationOnly(key, value) {
  if (VALIDATION_ONLY.has(key)) return true;
  if (key === "allOf" && value.every(isConditional)) return true;
  return key === "oneOf" && value.every(isRequiredOnly);
}

function refTarget(ref, rel, titles) {
  const [file, pointer = ""] = ref.split("#");
  if (!file) return pointer.replace(/^\/\$defs\//, "");
  const target = posix.join(posix.dirname(rel), file);
  if (!pointer) return titles.get(target);
  return pointer.replace(/^\/\$defs\//, "");
}

// Objects without declared properties are free-form maps for the generators.
function openObject(out) {
  const types = [out.type].flat();
  const free = types.includes("object") && !out.properties && out.additionalProperties === undefined;
  if (free) out.additionalProperties = true;
  return out;
}

function rewrite(node, rel, titles) {
  if (Array.isArray(node)) return node.map((n) => rewrite(n, rel, titles));
  if (node === null || typeof node !== "object") return node;
  return openObject(rewriteKeys(node, rel, titles));
}

function rewriteKeys(node, rel, titles) {
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("x-") || key === "$defs" || dropValidationOnly(key, value)) continue;
    out[key] = rewriteValue(key, value, rel, titles);
  }
  return out;
}

function rewriteValue(key, value, rel, titles) {
  if (key === "$ref") return `#/$defs/${refTarget(value, rel, titles)}`;
  if (key !== "properties") return rewrite(value, rel, titles);
  return Object.fromEntries(Object.entries(value).map(([name, sub]) => [name, rewrite(sub, rel, titles)]));
}

function addDef(defs, name, schema, rel) {
  if (defs[name]) throw new Error(`duplicate type name ${name} (${rel})`);
  defs[name] = schema;
}

function codegenFiles() {
  const node = schemaFiles("node").filter((rel) => rel !== GENERATED_MESSAGE);
  return [...node, ...schemaFiles("tools")];
}

export function buildBundle() {
  const files = codegenFiles().map((rel) => ({ rel, schema: loadSchema(rel) }));
  const titles = new Map(files.map(({ rel, schema }) => [rel, schema.title]));
  const defs = {};
  for (const { rel, schema } of files) {
    for (const [name, sub] of Object.entries(schema.$defs ?? {})) {
      if (sub.title && sub.title !== name) throw new Error(`${rel}: $defs key ${name} != title ${sub.title}`);
      addDef(defs, name, rewrite({ title: name, ...sub }, rel, titles), rel);
    }
    if (schema.type) addDef(defs, schema.title, rewrite(schema, rel, titles), rel);
  }
  const { Envelope, ...rest } = defs;
  return { $schema: DRAFT, ...Envelope, $defs: rest };
}

// ---- Go flavour: go-jsonschema maps nullable unions to interface{} and drops alias defs ----

const RAW = { type: "json.RawMessage", imports: ["encoding/json"] };

function isNull(s) {
  return s && s.type === "null" && Object.keys(s).length === 1;
}

function collapseNullable(s) {
  const out = { ...s };
  if (Array.isArray(out.type)) {
    const types = out.type.filter((t) => t !== "null");
    out.type = types.length === 1 ? types[0] : types;
  }
  const union = out.anyOf ?? out.oneOf;
  if (!union || union.length !== 2 || !union.some(isNull)) return out;
  const { anyOf, oneOf, ...rest } = out;
  return { ...rest, ...union.find((u) => !isNull(u)) };
}

function constToEnum(s) {
  if (!("const" in s)) return s;
  const { const: value, ...rest } = s;
  const type = Number.isInteger(value) ? "integer" : typeof value;
  return { type, ...rest, enum: [value] };
}

function inlineTimestamp(s) {
  if (s.$ref !== "#/$defs/Timestamp") return s;
  const { $ref, ...rest } = s;
  return { type: "string", format: "date-time", ...rest };
}

function goNode(node) {
  if (Array.isArray(node)) return node.map(goNode);
  if (node === null || typeof node !== "object") return node;
  const out = inlineTimestamp(constToEnum(collapseNullable(node)));
  for (const [key, value] of Object.entries(out)) {
    out[key] = key === "properties" ? mapValues(value, goNode) : goNode(value);
  }
  if (out.additionalProperties === true && !out.properties) out.goJSONSchema = RAW;
  return out;
}

function mapValues(obj, fn) {
  return Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, fn(v)]));
}

function resolveAlias(defs, def) {
  if (!def.$ref || def.type) return def;
  const { $ref, ...own } = def;
  const target = resolveAlias(defs, defs[$ref.replace("#/$defs/", "")]);
  return { ...target, ...own };
}

export function buildGoBundle(bundle = buildBundle()) {
  const go = goNode(bundle);
  go.properties.body = { ...go.properties.body, goJSONSchema: RAW };
  go.$defs = mapValues(go.$defs, (def) => resolveAlias(go.$defs, def));
  delete go.$defs.Timestamp;
  return go;
}

// ---- self-contained tool input schemas (session.open platform_tools[].input_schema) ----

function derefAll(node, defs) {
  if (Array.isArray(node)) return node.map((n) => derefAll(n, defs));
  if (node === null || typeof node !== "object") return node;
  if (node.$ref) {
    const { $ref, title, ...own } = node;
    return { ...derefAll(defs[$ref.replace("#/$defs/", "")], defs), ...own };
  }
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title") continue;
    out[key] = key === "properties" ? mapValues(value, (v) => derefAll(v, defs)) : derefAll(value, defs);
  }
  return out;
}

function inputSchema(bundle, title) {
  const { $schema, ...rest } = derefAll(bundle.$defs[title], bundle.$defs);
  return rest;
}

export function buildManifest(bundle = buildBundle()) {
  const messages = messageSchemas().map(({ type, schema }) => ({
    type,
    name: schema.title,
    direction: schema["x-direction"],
    reliable: schema["x-reliable"],
    key: schema["x-key"] ?? [],
  }));
  const tools = toolSchemas().map(({ name, schema }) => ({
    name,
    input: schema.title,
    result: Object.keys(schema.$defs ?? {}).find((k) => k.endsWith("Result")) ?? null,
    tiers: schema["x-tool"].tiers,
    blocking: schema["x-tool"].blocking,
    requires: schema["x-tool"].requires ?? null,
    description: schema.description,
    input_schema: inputSchema(bundle, schema.title),
  }));
  return { messages, tools };
}

function emit(path, text, check, stale) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === text) return;
  stale.push(path);
  if (!check) writeFileSync(path, text);
}

function run(check) {
  mkdirSync(join(ROOT, "gen"), { recursive: true });
  const stale = [];
  emit(join(SCHEMAS, GENERATED_MESSAGE), writeJsonText(buildMessageSchema()), check, stale);
  emit(join(ROOT, "gen/bundle.schema.json"), writeJsonText(buildBundle()), check, stale);
  emit(join(ROOT, "gen/bundle.go.schema.json"), writeJsonText(buildGoBundle()), check, stale);
  emit(join(ROOT, "gen/manifest.json"), writeJsonText(buildManifest()), check, stale);
  if (check && stale.length) {
    console.error("stale generated files (run make gen):\n  " + stale.join("\n  "));
    process.exit(1);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) run(process.argv.includes("--check"));
